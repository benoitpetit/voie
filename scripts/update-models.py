#!/usr/bin/env python3
"""Regenerate providers/generated_models.go from the awesome-free-ai-coding registry.

Usage: python3 scripts/update-models.py [path/to/registry.yaml]
Without an argument the current registry is downloaded from GitHub.
Run this when refreshing the curated free-model catalogue; voie itself never
fetches the registry at startup.
"""
import re
import sys
import urllib.request

import yaml

SOURCE = "https://raw.githubusercontent.com/mvalentsev/awesome-free-ai-coding/main/registry.yaml"
OUTPUT = "providers/generated_models.go"

# registry id -> (voie provider name, alias prefix)
PROVIDERS = {
    "openrouter-free": ("openrouter", "or"),
    "orcarouter": ("orcarouter", "ocr"),
    "groq-free": ("groq", "gq"),
    "google-ai-studio": ("google-ai-studio", "gs"),
    "nvidia-nim": ("nvidia-nim", "nv"),
    "zai-glm": ("zai", "zai"),
    "mistral-free": ("mistral", "mi"),
    "cloudflare-workers-ai": ("cloudflare-ai", "cf"),
    "cohere": ("cohere-trial", "coh"),
    "requesty": ("requesty", "rq"),
    "aihubmix": ("aihubmix", "ah"),
}


def slug(value):
    value = re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-")
    return value


def main():
    if len(sys.argv) > 1:
        with open(sys.argv[1], encoding="utf-8") as handle:
            raw = handle.read()
    else:
        with urllib.request.urlopen(SOURCE, timeout=60) as response:
            raw = response.read().decode("utf-8")
    entries = yaml.safe_load(raw)["entries"]
    by_id = {entry.get("id"): entry for entry in entries}

    lines = [
        "// Code generated by scripts/update-models.py; DO NOT EDIT.",
        "// Source: awesome-free-ai-coding registry.yaml (free model IDs by provider).",
        "package providers",
        "",
        "// RegistryModels maps a voie provider to its free-model aliases and upstream IDs.",
        "var RegistryModels = map[string]map[string]string{",
    ]
    seen = {}
    for registry_id, (provider, prefix) in PROVIDERS.items():
        entry = by_id.get(registry_id)
        if not entry:
            continue
        ids = (entry.get("api") or {}).get("model_ids") or []
        if not ids:
            continue
        lines.append(f'\t"{provider}": {{')
        for model_id in ids:
            alias = f"{prefix}-{slug(model_id)}"
            if alias in seen and seen[alias] != (provider, model_id):
                raise SystemExit(f"alias collision: {alias}")
            seen[alias] = (provider, model_id)
            lines.append(f'\t\t"{alias}": "{model_id}",')
        lines.append("\t},")
    lines += ["}", ""]
    with open(OUTPUT, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))
    print(f"wrote {OUTPUT}: {len(seen)} aliases")


if __name__ == "__main__":
    main()
